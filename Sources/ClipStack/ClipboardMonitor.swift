import AppKit

/// macOS no avisa cuando cambia el portapapeles, así que se consulta
/// `changeCount` periódicamente (es muy barato).
@MainActor
final class ClipboardMonitor {
    private let store: HistoryStore
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount

    /// changeCount producido por la propia app al pegar; se ignora.
    var ignoreChangeCount: Int?

    /// Se llama cada vez que entra un clip nuevo en el historial.
    var onNewClip: (@MainActor () -> Void)?

    private let concealedTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    init(store: HistoryStore) {
        self.store = store
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount

        if lastChange == ignoreChangeCount { return }
        if Preferences.shared.isPaused { return }

        let types = pb.types ?? []
        if types.contains(where: concealedTypes.contains) { return }

        let app = NSWorkspace.shared.frontmostApplication
        if let id = app?.bundleIdentifier, Preferences.shared.ignoredBundleIDs.contains(id) { return }

        if add(from: pb, app: app) { onNewClip?() }
    }

    private func add(from pb: NSPasteboard, app: NSRunningApplication?) -> Bool {
        // 1) Archivos copiados en Finder
        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return store.addFiles(urls, app: app)
        }

        // 2) Texto
        if let text = pb.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return store.addText(text, app: app)
        }

        // 3) Imágenes (capturas, imágenes copiadas del navegador, etc.)
        if let png = pb.data(forType: .png) {
            return store.addImage(png: png, app: app)
        } else if let tiff = pb.data(forType: .tiff),
                  let rep = NSBitmapImageRep(data: tiff),
                  let png = rep.representation(using: .png, properties: [:]) {
            return store.addImage(png: png, app: app)
        }
        return false
    }
}
